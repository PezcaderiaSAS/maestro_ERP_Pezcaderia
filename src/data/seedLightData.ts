/**
 * Retorna el mapa canónico de stock inicial por SKU para las bodegas de prueba.
 * Cada producto cuenta con un stock positivo entre 20 y 100 unidades.
 */
export function getSeedLightStock(): Record<string, number> {
  const stockMap: Record<string, number> = {};
  for (const prod of SEED_LIGHT_PRODUCTOS) {
    // Asignar cantidades estándar en base a la categoría ABC
    if (prod.categoriaABC === 'A') {
      stockMap[prod.sku] = 50;
    } else if (prod.categoriaABC === 'B') {
      stockMap[prod.sku] = 75;
    } else {
      stockMap[prod.sku] = 100;
    }
  }
  return stockMap;
}
